"""
Character Set Generator.

A character set answers "what does this person look like?" once, as a
*version* of canonical views - front, side, back, full body, an expression -
generated from one identity spec. Versions accumulate and exactly one is
approved as canonical; that approved version is the only thing downstream
generation is conditioned on.

Three rules hold throughout:

* **Approval is a pointer, never a deletion.** A newer approved version
  supersedes the old one. Every version keeps its images, so an approved take
  generated months ago can still be explained.
* **Views are real references.** Generated bytes are stored through
  :mod:`app.services.reference_bible` onto a sheet the set owns, so a canonical
  view reaches a provider through the same validated, ownership-checked path as
  a hand-uploaded plate. There is exactly one way an image can condition a job.
* **Identity has a digest.** ``canonical_digest`` folds the approved version's
  spec and image hashes into one value, which is what selective staleness
  compares against when the canonical identity moves.
"""

import hashlib
import json
import logging
from datetime import datetime, timezone
from typing import Any

from sqlalchemy.orm import Session

from app.models import (
    CharacterSet,
    CharacterSetVersion,
    CharacterSetView,
    ReferenceImage,
    ReferenceSheet,
)
from app.services import reference_bible

logger = logging.getLogger("cas.character_sets")


# ---------------------------------------------------------------------------
# Vocabulary
# ---------------------------------------------------------------------------

#: The canonical view slots a version may contain, in the order a character
#: sheet is conventionally read. Deliberately closed: each slot carries a
#: different instruction to the generator, and an unrecognised one would
#: silently produce an unlabelled image that nothing downstream could use.
VIEW_SLOTS: tuple[str, ...] = (
    "front",
    "three_quarter",
    "side",
    "back",
    "full_body",
    "expression",
    "pose",
)

#: What each slot asks the generator for. Appended to the identity spec when a
#: view's prompt is compiled, so the same spec yields consistent coverage.
SLOT_DIRECTIVES: dict[str, str] = {
    "front": (
        "front-facing character reference view, head-on, neutral expression, "
        "arms relaxed at the sides, even studio lighting, plain background"
    ),
    "three_quarter": (
        "three-quarter turn character reference view, body angled 45 degrees, "
        "neutral expression, even studio lighting, plain background"
    ),
    "side": (
        "full profile character reference view, exact side-on, neutral "
        "expression, even studio lighting, plain background"
    ),
    "back": (
        "rear character reference view, facing directly away, even studio "
        "lighting, plain background"
    ),
    "full_body": (
        "full-body character reference view, head to feet in frame, standing "
        "in a neutral A-pose, even studio lighting, plain background"
    ),
    "expression": (
        "expression sheet close-up of the same character, head and shoulders, "
        "even studio lighting, plain background"
    ),
    "pose": (
        "action pose reference of the same character, full body in frame, "
        "even studio lighting, plain background"
    ),
}

#: The default sheet a new version generates when the caller names no slots.
DEFAULT_SLOTS: tuple[str, ...] = ("front", "side", "back", "full_body")

STATUS_DRAFT = "Draft"
STATUS_GENERATING = "Generating"
STATUS_NEEDS_REVIEW = "NeedsReview"
STATUS_APPROVED = "Approved"
STATUS_SUPERSEDED = "Superseded"
STATUS_FAILED = "Failed"

VIEW_PENDING = "Pending"
VIEW_GENERATING = "Generating"
VIEW_READY = "Ready"
VIEW_FAILED = "Failed"

#: Set fields a client may write. Anything else - project, sheet, canonical
#: pointer, digests - is ours.
EDITABLE_SET_FIELDS: tuple[str, ...] = (
    "name",
    "character_id",
    "appearance",
    "proportions",
    "wardrobe",
    "palette",
    "identity_tokens",
    "negative_tokens",
    "notes",
)


class CharacterSetError(Exception):
    """A character set operation was refused, with a machine-readable reason."""

    def __init__(self, message: str, code: str, *, shot_ids: list[str] | None = None):
        super().__init__(message)
        self.code = code
        #: Populated when something still depends on what was being changed.
        self.shot_ids = shot_ids or []


def _utcnow() -> datetime:
    return datetime.now(timezone.utc)


def _digest(payload: Any) -> str:
    encoded = json.dumps(payload, sort_keys=True, ensure_ascii=False, default=str)
    return hashlib.sha256(encoded.encode("utf-8")).hexdigest()


# ---------------------------------------------------------------------------
# Spec
# ---------------------------------------------------------------------------

def spec_snapshot(character_set: CharacterSet) -> dict[str, str]:
    """The identity text a version is generated from, as a plain mapping."""
    return {
        "name": character_set.name or "",
        "appearance": character_set.appearance or "",
        "proportions": character_set.proportions or "",
        "wardrobe": character_set.wardrobe or "",
        "palette": character_set.palette or "",
        "identity_tokens": character_set.identity_tokens or "",
        "negative_tokens": character_set.negative_tokens or "",
        # The picture is part of who the character is, so swapping it has to
        # move the digest exactly as rewriting the appearance does - otherwise
        # an approved sheet keeps reading as canonical for a different subject.
        "source_image_id": character_set.source_image_id or "",
    }


def spec_digest(character_set: CharacterSet) -> str:
    return _digest(spec_snapshot(character_set))


def identity_description(character_set: CharacterSet) -> str:
    """The spec as one sentence-per-facet block, for prompt compilation."""
    snapshot = spec_snapshot(character_set)
    parts = [snapshot["name"]]
    for field in ("appearance", "proportions", "wardrobe"):
        value = snapshot[field].strip()
        if value:
            parts.append(value)
    palette = snapshot["palette"].strip()
    if palette:
        parts.append("colour palette: " + palette)
    tokens = snapshot["identity_tokens"].strip()
    if tokens:
        parts.append(tokens)
    return ". ".join(part.rstrip(". ") for part in parts if part).strip()


def compile_view_prompt(character_set: CharacterSet, slot: str) -> str:
    """The positive prompt for one view of one character."""
    directive = SLOT_DIRECTIVES.get(slot, slot.replace("_", " ") + " reference view")
    identity = identity_description(character_set)
    return f"{directive}. {identity}" if identity else directive


