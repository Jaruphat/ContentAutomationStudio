def normalise_slots(slots: list[str] | None) -> list[str]:
    """Validate requested slots, keeping the caller's order and dropping dupes."""
    requested = [str(slot or "").strip().lower() for slot in (slots or [])]
    requested = [slot for slot in requested if slot]
    if not requested:
        raise CharacterSetError(
            "A character set version needs at least one view. Choose from: "
            + ", ".join(VIEW_SLOTS)
            + ".",
            "no_slots",
        )
    seen: set[str] = set()
    ordered: list[str] = []
    for slot in requested:
        if slot not in VIEW_SLOTS:
            raise CharacterSetError(
                f"'{slot}' is not a character view. Use one of: "
                + ", ".join(VIEW_SLOTS)
                + ".",
                "invalid_slot",
            )
        if slot in seen:
            continue
        seen.add(slot)
        ordered.append(slot)
    return ordered


def create_version(
    db: Session,
    character_set: CharacterSet,
    *,
    slots: list[str] | None = None,
    provider_id: str = "",
    model: str = "",
    workflow_id: str | None = None,
    request_params: dict[str, Any] | None = None,
    seed: int | None = None,
    notes: str = "",
) -> CharacterSetVersion:
    """Open a new draft version with one pending view per requested slot."""
    ordered = normalise_slots(slots)

    highest = (
        db.query(CharacterSetVersion)
        .filter(CharacterSetVersion.character_set_id == character_set.id)
        .order_by(CharacterSetVersion.version.desc())
        .first()
    )
    next_version = (highest.version + 1) if highest else 1

    version = CharacterSetVersion(
        character_set_id=character_set.id,
        project_id=character_set.project_id,
        version=next_version,
        status=STATUS_DRAFT,
        spec_snapshot=spec_snapshot(character_set),
        spec_sha256=spec_digest(character_set),
        provider_id=provider_id or "",
        model=model or "",
        workflow_id=workflow_id,
        request_params=dict(request_params or {}),
        seed=seed,
        notes=notes or "",
    )
    db.add(version)
    db.flush()

    for order, slot in enumerate(ordered):
        db.add(CharacterSetView(
            version_id=version.id,
            character_set_id=character_set.id,
            project_id=character_set.project_id,
            slot=slot,
            label=slot.replace("_", " ").title(),
            order=order,
            view_prompt=compile_view_prompt(character_set, slot),
            status=VIEW_PENDING,
            provider_id=provider_id or "",
            model=model or "",
            workflow_id=workflow_id,
            seed=seed,
        ))

    db.flush()
    version.content_sha256 = version_content_digest(db, version)
    db.commit()
    db.refresh(version)
    return version


def list_versions(db: Session, character_set: CharacterSet) -> list[CharacterSetVersion]:
    return (
        db.query(CharacterSetVersion)
        .filter(CharacterSetVersion.character_set_id == character_set.id)
        .order_by(CharacterSetVersion.version)
        .all()
    )


def get_version(
    db: Session, character_set: CharacterSet, version_id: str
) -> CharacterSetVersion | None:
    return (
        db.query(CharacterSetVersion)
        .filter(
            CharacterSetVersion.id == version_id,
            CharacterSetVersion.character_set_id == character_set.id,
        )
        .first()
    )


def list_views(db: Session, version: CharacterSetVersion) -> list[CharacterSetView]:
    return (
        db.query(CharacterSetView)
        .filter(CharacterSetView.version_id == version.id)
        .order_by(CharacterSetView.order)
        .all()
    )


def version_content_digest(db: Session, version: CharacterSetVersion) -> str:
    """The spec plus every view's image hash, in view order.

    Image *hashes* rather than ids: regenerating a view to identical bytes is
    not a change, and should not invalidate work already approved against it.
    """
    views = list_views(db, version)
    return _digest({
        "spec": version.spec_sha256 or "",
        "views": [
            {
                "slot": view.slot,
                "sha256": view.image.sha256 if view.image is not None else "",
            }
            for view in views
        ],
    })


