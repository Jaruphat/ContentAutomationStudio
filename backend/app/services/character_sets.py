# Approval
# ---------------------------------------------------------------------------

def approve_version(
    db: Session, version: CharacterSetVersion
) -> CharacterSetVersion:
    """Make this version the set's canonical identity.

    Every view must carry an image: a half-generated sheet approved as
    canonical would condition later shots on a subset of the identity without
    saying so. The previously approved version is superseded, not deleted.
    """
    views = list_views(db, version)
    missing = [view.slot for view in views if not view.reference_image_id]
    if missing:
        raise CharacterSetError(
            "Every view must have an image before this version can be "
            "approved as canonical. Still missing: " + ", ".join(missing) + ".",
            "views_incomplete",
        )

    character_set = (
        db.query(CharacterSet)
        .filter(CharacterSet.id == version.character_set_id)
        .first()
    )
    if character_set is None:
        raise CharacterSetError("This version has no character set.", "set_missing")

    for other in list_versions(db, character_set):
        if other.id != version.id and other.status == STATUS_APPROVED:
            other.status = STATUS_SUPERSEDED

    version.status = STATUS_APPROVED
    version.approved_at = _utcnow()
    version.content_sha256 = version_content_digest(db, version)
    character_set.approved_version_id = version.id
    db.commit()
    db.refresh(version)
    return version


def unapprove_version(
    db: Session, version: CharacterSetVersion
) -> CharacterSetVersion:
    """Withdraw canonical status, leaving the set with no canonical identity."""
    character_set = (
        db.query(CharacterSet)
        .filter(CharacterSet.id == version.character_set_id)
        .first()
    )
    if character_set is not None and character_set.approved_version_id == version.id:
        character_set.approved_version_id = None
    if version.status == STATUS_APPROVED:
        version.status = STATUS_NEEDS_REVIEW
    db.commit()
    db.refresh(version)
    return version


def approved_version(
    db: Session, character_set: CharacterSet
) -> CharacterSetVersion | None:
    if not character_set.approved_version_id:
        return None
    return (
        db.query(CharacterSetVersion)
        .filter(CharacterSetVersion.id == character_set.approved_version_id)
        .first()
    )


def approved_version_is_current(
    db: Session, character_set: CharacterSet
) -> bool:
    """Whether the canonical version was generated from today's spec.

    False means the identity text has been edited since the canonical views
    were made. That is surfaced, never auto-corrected: regenerating a character
    sheet is a decision with a cost, and only the user makes it.
    """
    version = approved_version(db, character_set)
    if version is None:
        return False
    return (version.spec_sha256 or "") == spec_digest(character_set)


# ---------------------------------------------------------------------------
# Resolution
# ---------------------------------------------------------------------------

def canonical_digest(db: Session, character_set: CharacterSet) -> str:
    """One value covering the canonical identity a generation would use.

    Empty when nothing is approved, which is itself meaningful: a shot bound to
    a set with no canonical version hashes differently from one bound to a set
    that has one.
    """
    version = approved_version(db, character_set)
    if version is None:
        return ""
    return version.content_sha256 or version_content_digest(db, version)


def resolve_canonical_images(
    db: Session, project_id: str, set_ids: list[str]
) -> list[ReferenceImage]:
    """The approved canonical view images for these sets, in a stable order.

    Sets are visited in the order asked and their views in slot order, so the
    identity references a job records are reproducible. A set from another
    project, an unknown id, or a set with nothing approved contributes nothing:
    the caller's preflight is what turns those into a visible blocker.
    """
    if not set_ids:
        return []

    found = {
        character_set.id: character_set
        for character_set in db.query(CharacterSet)
        .filter(CharacterSet.id.in_(set_ids))
        .all()
    }

    images: list[ReferenceImage] = []
    seen: set[str] = set()
    for set_id in set_ids:
        character_set = found.get(set_id)
        if character_set is None or character_set.project_id != project_id:
            continue
        version = approved_version(db, character_set)
        if version is None:
            continue
        for view in list_views(db, version):
            image = view.image
            if image is None or image.id in seen:
                continue
            seen.add(image.id)
            images.append(image)
    return images


def canonical_problems(
    db: Session, project_id: str, set_ids: list[str]
) -> list[str]:
    """Why the requested canonical identity cannot be used, in plain words.

    Returned as blockers rather than resolved silently: a shot that names a
    character set is asking to be conditioned on it, so a set with nothing
    approved must stop the run instead of producing an unconditioned render.
    """
    problems: list[str] = []
    if not set_ids:
        return problems

    found = {
        character_set.id: character_set
        for character_set in db.query(CharacterSet)
        .filter(CharacterSet.id.in_(set_ids))
        .all()
    }
    for set_id in set_ids:
        character_set = found.get(set_id)
        if character_set is None:
            problems.append(f"Character set {set_id} no longer exists.")
            continue
        if character_set.project_id != project_id:
            problems.append(
                f"Character set {set_id} belongs to another project and cannot "
                f"be used here."
            )
            continue
        version = approved_version(db, character_set)
        if version is None:
            problems.append(
                f"Character set '{character_set.name}' has no approved "
                f"canonical version. Generate and approve one first."
            )
            continue
        for view in list_views(db, version):
            if view.image is None:
                problems.append(
                    f"Character set '{character_set.name}' version "
                    f"{version.version} is missing its {view.slot} view image."
                )
    return problems
