# View images
# ---------------------------------------------------------------------------

def attach_view_image(
    db: Session,
    view: CharacterSetView,
    *,
    data: bytes,
    content_type: str = "",
    original_filename: str = "",
    provenance: dict[str, Any] | None = None,
) -> CharacterSetView:
    """Store the bytes for one view and mark it ready.

    Validation, hashing and the stored path all come from the reference bible,
    so a generated view is indistinguishable downstream from an uploaded one -
    which is the point.
    """
    version = (
        db.query(CharacterSetVersion)
        .filter(CharacterSetVersion.id == view.version_id)
        .first()
    )
    if version is None:
        raise CharacterSetError("This view has no version.", "version_missing")
    character_set = (
        db.query(CharacterSet)
        .filter(CharacterSet.id == version.character_set_id)
        .first()
    )
    sheet = backing_sheet(db, character_set) if character_set else None
    if sheet is None:
        raise CharacterSetError(
            "This character set has no reference sheet to store views on.",
            "sheet_missing",
        )

    detail = dict(provenance or {})
    image = reference_bible.store_image(
        db,
        sheet=sheet,
        data=data,
        original_filename=original_filename or f"{view.slot}.png",
        content_type=content_type,
        role="canonical",
        caption=f"{character_set.name} - {view.label or view.slot}",
        source="character_set",
        source_detail={
            "character_set_id": character_set.id,
            "character_set_version": version.version,
            "view_slot": view.slot,
            **detail,
        },
    )

    view.reference_image_id = image.id
    view.status = VIEW_READY
    view.error_message = ""
    view.provenance = {**dict(view.provenance or {}), **detail}
    if "provider_id" in detail:
        view.provider_id = str(detail["provider_id"] or "")
    if "model" in detail:
        view.model = str(detail["model"] or "")
    if "seed" in detail and isinstance(detail["seed"], int):
        view.seed = detail["seed"]
    db.flush()

    version.content_sha256 = version_content_digest(db, version)
    if version.status == STATUS_DRAFT and all(
        v.reference_image_id for v in list_views(db, version)
    ):
        version.status = STATUS_NEEDS_REVIEW
    db.commit()
    db.refresh(view)
    return view


def fail_view(db: Session, view: CharacterSetView, message: str) -> CharacterSetView:
    """Record that one view could not be generated, with the reason."""
    view.status = VIEW_FAILED
    view.error_message = (message or "")[:1000]
    version = (
        db.query(CharacterSetVersion)
        .filter(CharacterSetVersion.id == view.version_id)
        .first()
    )
    if version is not None and version.status in (STATUS_DRAFT, STATUS_GENERATING):
        version.status = STATUS_FAILED
    db.commit()
    db.refresh(view)
    return view


