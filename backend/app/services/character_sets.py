def create_set(
    db: Session,
    *,
    project_id: str,
    name: str,
    character_id: str | None = None,
    appearance: str = "",
    proportions: str = "",
    wardrobe: str = "",
    palette: str = "",
    identity_tokens: str = "",
    negative_tokens: str = "",
    notes: str = "",
) -> CharacterSet:
    """Create a character set and the reference sheet its views live on."""
    if not (name or "").strip():
        raise CharacterSetError(
            "A character set needs a name so it can be recognised in the "
            "storyboard.",
            "missing_name",
        )

    character_set = CharacterSet(
        project_id=project_id,
        character_id=character_id or None,
        name=name.strip(),
        appearance=appearance or "",
        proportions=proportions or "",
        wardrobe=wardrobe or "",
        palette=palette or "",
        identity_tokens=identity_tokens or "",
        negative_tokens=negative_tokens or "",
        notes=notes or "",
    )
    db.add(character_set)
    db.flush()

    sheet = reference_bible.create_sheet(
        db,
        project_id=project_id,
        kind="character",
        name=character_set.name,
        subject_ref_id=character_id or None,
        canonical_description=identity_description(character_set),
        identity_tokens=identity_tokens or "",
        negative_tokens=negative_tokens or "",
        notes="Generated character set views.",
    )
    character_set.reference_sheet_id = sheet.id
    db.commit()
    db.refresh(character_set)
    return character_set


def attach_source_image(
    db: Session,
    character_set: CharacterSet,
    *,
    data: bytes,
    content_type: str = "",
    original_filename: str = "",
) -> ReferenceImage:
    """Attach the picture this identity is derived from.

    Filed on the same sheet as the views but with role ``source``: the store
    is content-addressed and validated in one place, and the role is what
    keeps a photograph of the subject from being resolved as a canonical view
    and sent to a shot as one.

    Replacing it moves the identity spec, so a sheet approved from the old
    picture reads as out of date rather than staying canonical for somebody
    else's face.
    """
    sheet = backing_sheet(db, character_set)
    if sheet is None:
        raise CharacterSetError(
            "This character set has no reference sheet to store a source "
            "image on.",
            "sheet_missing",
        )
    image = reference_bible.store_image(
        db,
        sheet=sheet,
        data=data,
        original_filename=original_filename or "source.png",
        content_type=content_type,
        role="source",
        caption=f"{character_set.name} - source image",
        source="upload",
        source_detail={"character_set_id": character_set.id},
    )
    character_set.source_image_id = image.id
    db.commit()
    db.refresh(character_set)
    return image


def update_set(
    db: Session, character_set: CharacterSet, changes: dict[str, Any]
) -> CharacterSet:
    """Apply an edit to a set's identity spec.

    The approved version is left exactly where it is. Editing the spec does not
    retroactively change what was approved; it changes what the *next* version
    would be generated from, and the difference is what
    :func:`approved_version_is_current` reports.
    """
    if "name" in changes and changes["name"] is not None:
        if not str(changes["name"]).strip():
            raise CharacterSetError("A character set needs a name.", "missing_name")
        changes = {**changes, "name": str(changes["name"]).strip()}

    for field, value in changes.items():
        if field in EDITABLE_SET_FIELDS and value is not None:
            setattr(character_set, field, value)

    sheet = backing_sheet(db, character_set)
    if sheet is not None:
        reference_bible.update_sheet(
            db,
            sheet,
            {
                "name": character_set.name,
                "canonical_description": identity_description(character_set),
                "identity_tokens": character_set.identity_tokens or "",
                "negative_tokens": character_set.negative_tokens or "",
            },
        )
    db.commit()
    db.refresh(character_set)
    return character_set


def list_sets(db: Session, project_id: str) -> list[CharacterSet]:
    return (
        db.query(CharacterSet)
        .filter(CharacterSet.project_id == project_id)
        .order_by(CharacterSet.name)
        .all()
    )


def get_set(db: Session, project_id: str, set_id: str) -> CharacterSet | None:
    """Fetch one set, scoped to its project so a foreign id simply misses."""
    return (
        db.query(CharacterSet)
        .filter(
            CharacterSet.id == set_id,
            CharacterSet.project_id == project_id,
        )
        .first()
    )


def backing_sheet(db: Session, character_set: CharacterSet) -> ReferenceSheet | None:
    if not character_set.reference_sheet_id:
        return None
    return (
        db.query(ReferenceSheet)
        .filter(ReferenceSheet.id == character_set.reference_sheet_id)
        .first()
    )


def delete_set(db: Session, character_set: CharacterSet, *, force: bool = False) -> list[str]:
    """Delete a set, its versions and the sheet its views live on.

    Refused while a shot still binds to it, unless forced: dropping the
    canonical identity out from under a shot would silently un-condition its
    next generation.
    """
    dependents = shots_binding(db, [character_set.id])
    if dependents and not force:
        raise CharacterSetError(
            f"{len(dependents)} shot(s) still use this character set. Unbind "
            f"them first, or delete it with force to detach them.",
            "character_set_in_use",
            shot_ids=[shot.id for shot in dependents],
        )

    detached: list[str] = []
    for shot in dependents:
        shot.character_set_ids = [
            value
            for value in (shot.character_set_ids or [])
            if value != character_set.id
        ]
        detached.append(shot.id)

    sheet = backing_sheet(db, character_set)
    db.delete(character_set)
    db.flush()
    if sheet is not None:
        reference_bible.delete_sheet(db, sheet, force=True)
    db.commit()
    return detached


def shots_binding(db: Session, set_ids: list[str]):
    """Every shot that binds one of these character sets.

    ``character_set_ids`` is a JSON list, which SQLite cannot index into
    portably, so membership is tested in Python over the project's shots -
    projects here hold tens of shots, not millions.
    """
    from app.models import Scene, Shot

    if not set_ids:
        return []
    wanted = set(set_ids)
    project_ids = {
        row.project_id
        for row in db.query(CharacterSet).filter(CharacterSet.id.in_(set_ids)).all()
    }
    if not project_ids:
        return []
    shots = (
        db.query(Shot)
        .join(Scene, Shot.scene_id == Scene.id)
        .filter(Scene.project_id.in_(project_ids))
        .all()
    )
    return [s for s in shots if wanted & set(s.character_set_ids or [])]


